"""Network fetch (run once, outputs are cached and immutable): BLASTP the
A. thaliana FLK reference (Q9SR13) against NCBI RefSeq proteins, one search
per taxonomic partition, for the expanded angiosperm sampling requested in
revision (Reviewer 1, comment 1).

Uses the NCBI BLAST URL API (https://blast.ncbi.nlm.nih.gov/Blast.cgi),
following NCBI's usage guidelines: one search submitted at a time, status
polled no more than once per minute per RID. No e-mail address or other
personal identifier is sent.

Outputs (never regenerated by reproduce_all.py, which works offline):
- data/expanded/blast/<partition>.json   raw BLAST JSON2_S result
- data/expanded/blast/blast_runs.tsv      RID, query, database, Entrez
                                          filter, parameters, date
"""
import argparse
import csv
import datetime as dt
import json
import re
import sys
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from flk_repeat.paths import DATA_DIR  # noqa: E402
from flk_repeat.sequence import load_flk_record  # noqa: E402

BLAST_URL = "https://blast.ncbi.nlm.nih.gov/Blast.cgi"
OUT_DIR = DATA_DIR / "expanded" / "blast"

# Entrez organism filters. Brassicaceae (txid3700) is searched separately so
# that it cannot crowd the hit list of the other partitions.
PARTITIONS = {
    "monocots": "txid4447[ORGN]",
    "eudicots_non_brassicaceae": "txid71240[ORGN] NOT txid3700[ORGN]",
    "other_angiosperms": "txid3398[ORGN] NOT txid71240[ORGN] NOT txid4447[ORGN]",
    "brassicaceae": "txid3700[ORGN]",
}
PARAMS = {
    "PROGRAM": "blastp",
    "DATABASE": "refseq_protein",
    "HITLIST_SIZE": "2000",
    "EXPECT": "1e-5",
    "MATRIX_NAME": "BLOSUM62",
    "TOOL": "flk-repeat-revision",
}


def submit(query: str, entrez: str) -> tuple[str, int]:
    data = {"CMD": "Put", "QUERY": query, "ENTREZ_QUERY": entrez, **PARAMS}
    r = requests.post(BLAST_URL, data=data, timeout=120)
    r.raise_for_status()
    rid = re.search(r"RID = (\S+)", r.text)
    rtoe = re.search(r"RTOE = (\d+)", r.text)
    if not rid:
        raise RuntimeError(f"no RID in response: {r.text[:500]}")
    return rid.group(1), int(rtoe.group(1)) if rtoe else 60


def wait(rid: str, first_wait: int) -> None:
    time.sleep(max(first_wait, 30))
    while True:
        r = requests.get(BLAST_URL, params={"CMD": "Get", "FORMAT_OBJECT": "SearchInfo", "RID": rid}, timeout=120)
        status = re.search(r"Status=(\w+)", r.text)
        status = status.group(1) if status else "UNKNOWN"
        print(f"  {rid}: {status}", flush=True)
        if status == "READY":
            return
        if status in ("FAILED", "UNKNOWN"):
            raise RuntimeError(f"BLAST {rid} ended with status {status}")
        time.sleep(65)


def fetch(rid: str) -> str:
    r = requests.get(BLAST_URL, params={"CMD": "Get", "RID": rid, "FORMAT_TYPE": "JSON2_S"}, timeout=600)
    r.raise_for_status()
    return r.text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--partitions", nargs="*", default=list(PARTITIONS))
    args = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    query = load_flk_record()["sequence"]
    log_path = OUT_DIR / "blast_runs.tsv"
    new_log = not log_path.exists()
    with open(log_path, "a", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, delimiter="\t")
        if new_log:
            w.writerow(["partition", "rid", "query_accession", "database", "entrez_query",
                        "hitlist_size", "expect", "matrix", "run_date_utc", "output_file"])
        for name in args.partitions:
            out = OUT_DIR / f"{name}.json"
            if out.exists():
                print(f"{name}: cached, skipping")
                continue
            entrez = PARTITIONS[name]
            pending = OUT_DIR / f"{name}.pending.json"
            if pending.exists():
                job = json.loads(pending.read_text(encoding="utf-8"))
                rid, rtoe = job["rid"], 0
                print(f"{name}: resuming RID {rid}", flush=True)
            else:
                print(f"{name}: submitting ({entrez})", flush=True)
                rid, rtoe = submit(query, entrez)
                pending.write_text(json.dumps({"rid": rid, "rtoe": rtoe,
                                               "partition": name, "entrez_query": entrez,
                                               "submitted_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")},
                                              indent=2) + "\n", encoding="utf-8")
            wait(rid, rtoe)
            out.write_text(fetch(rid), encoding="utf-8")
            w.writerow([name, rid, "Q9SR13", PARAMS["DATABASE"], entrez, PARAMS["HITLIST_SIZE"],
                        PARAMS["EXPECT"], PARAMS["MATRIX_NAME"],
                        dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                        out.relative_to(DATA_DIR.parent).as_posix()])
            fh.flush()
            pending.unlink()
            print(f"{name}: saved {out.name}", flush=True)
            time.sleep(15)


if __name__ == "__main__":
    main()
